#!/usr/bin/env node
// CLONE FRAME — the agent's self-map generator.
//
// Emits agent/STRUCTURE.md: a monorepo-style branch tree of the WHOLE body — panels,
// kernel modules, bridge modules, tools, the agent's own mind (extensions · skills ·
// lessons), tests, integrations — every branch read from the REAL sources, never
// hand-written. tools/build.mjs runs it on every build, so every edit that ships
// refreshes the tree; bridge/pi.mjs ensureWorkspace() then syncs it into the live
// workspace (~/.clone-frame-hub/agent). The header carries the commit + timestamp:
// that stamp IS the agent's change-awareness — a new stamp means the body changed.
//
// Run standalone: node tools/gen-structure-tree.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { execSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'agent', 'STRUCTURE.md');

// First human sentence of a source file's head comment — the file's own one-liner.
function headline(file, max = 96) {
  let text = '';
  try { text = readFileSync(file, 'utf8').slice(0, 2000); } catch { return ''; }
  for (const raw of text.split('\n').slice(0, 14)) {
    const l = raw.replace(/^\s*(\/\/|\/\*+|\*+|#!?)\s?/, '').replace(/[─═-]{4,}/g, '').trim();
    if (!l || /env node|^\/?usr\/bin/.test(l)) continue;
    return l.slice(0, max);
  }
  return '';
}

function listFiles(dir, ext) {
  try { return readdirSync(path.join(ROOT, dir)).filter((f) => f.endsWith(ext)).sort(); } catch { return []; }
}
function listDirs(dir) {
  try { return readdirSync(path.join(ROOT, dir)).filter((f) => { try { return statSync(path.join(ROOT, dir, f)).isDirectory(); } catch { return false; } }).sort(); } catch { return []; }
}

// Kernel modules: every top-level `const X=(()=>` IIFE in the single-file app.
function kernelModules() {
  let html = '';
  try { html = readFileSync(path.join(ROOT, 'web', 'index.html'), 'utf8'); } catch { return []; }
  const out = [];
  const re = /^const ([A-Z]\w+)=\(\(\)=>/gm;
  let m; while ((m = re.exec(html))) out.push(m[1]);
  return out;
}

// Branch renderer: entries = [name, note]; returns │ ├─ └─ lines under a prefix.
function branch(entries, prefix, pad = 26) {
  return entries.map(([n, note], i) => {
    const tee = i === entries.length - 1 ? '└─ ' : '├─ ';
    return prefix + tee + (note ? n.padEnd(pad) + ' ' + note : n);
  });
}

export function genStructureTree({ silent = false } = {}) {
  let sha = 'unversioned';
  try { sha = execSync('git rev-parse --short HEAD', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* shipped bundle without git */ }

  // Panels: prefer the machine map genAppMap just wrote (same build), fall back to files.
  let panels = [];
  try {
    const map = JSON.parse(readFileSync(path.join(ROOT, 'context', 'app-map.json'), 'utf8'));
    panels = (map.panels || []).map((p) => [p.key + '.js', (p.title || '') + (p.sub ? ' — ' + p.sub : '')]);
  } catch {
    panels = listFiles('web/panels', '.js').map((f) => [f, headline(path.join(ROOT, 'web/panels', f))]);
  }

  const bridge = listFiles('bridge', '.mjs').map((f) => [f, headline(path.join(ROOT, 'bridge', f))]);
  const tools = listFiles('tools', '.mjs').map((f) => [f, headline(path.join(ROOT, 'tools', f))]);
  const exts = listFiles('agent/.pi/extensions', '.ts').map((f) => [f, headline(path.join(ROOT, 'agent/.pi/extensions', f))]);
  const skills = listDirs('agent/.pi/skills').map((d) => [d + '/', '']);
  const lessons = listFiles('agent/LESSONS', '.md').filter((f) => f !== 'README.md').map((f) => [f, '']);
  const integrations = listDirs('integrations').map((d) => [d + '/', '']);
  const testCount = listFiles('tests', '.test.mjs').length + listFiles('tools', '.test.mjs').length;
  const kern = kernelModules();

  const L = [];
  L.push('# CLONE FRAME HUB — BODY TREE');
  L.push('');
  L.push(`Generated by \`tools/gen-structure-tree.mjs\` on every build · commit \`${sha}\` · ${new Date().toISOString()}`);
  L.push('');
  L.push('This is your body, mapped from the real sources — never hand-written, never stale');
  L.push('past the last build. **A new stamp above means the body changed since you last read');
  L.push('this file.** Use the tree to locate any capability before working on or with the app.');
  L.push('');
  L.push('```');
  L.push('clone-frame-hub');
  L.push('├─ web/                        the FACE — one self-contained index.html (single-writer)');
  L.push(`│  ├─ index.html               kernel IIFE modules: ${kern.join(' · ') || 'Bus · Store · Grid · Panels'}`);
  L.push('│  ├─ scripts/core/kernel.js   ' + headline(path.join(ROOT, 'web/scripts/core/kernel.js')));
  L.push('│  └─ panels/                  one file per panel (compiled in by tools/build.mjs)');
  L.push(...branch(panels, '│     '));
  L.push('├─ bridge/                     the HANDS — HUB Bridge daemon (127.0.0.1:8765, token-gated)');
  L.push(...branch(bridge, '│  '));
  L.push('├─ tools/                      build & generators (single-file assembler, app map, this tree)');
  L.push(...branch(tools, '│  '));
  L.push('├─ agent/                      the MIND — your workspace, synced to ~/.clone-frame-hub/agent');
  L.push('│  ├─ AGENTS.md                curriculum — who you are and how you work');
  L.push('│  ├─ STRUCTURE.md             this file');
  L.push('│  ├─ LESSONS/                 your own training log, one lesson per fall');
  L.push(...branch(lessons, '│  │  ', 40));
  L.push('│  └─ .pi/');
  L.push('│     ├─ extensions/           your tools into the app (TypeScript, loaded by pi)');
  L.push(...branch(exts, '│     │  '));
  L.push('│     └─ skills/               deep procedures you can invoke');
  L.push(...branch(skills, '│        ', 40));
  L.push('├─ integrations/               self-contained optional integrations');
  L.push(...branch(integrations, '│  ', 40));
  L.push(`├─ tests/                      ${testCount} node --test files — run: node --test tests/*.test.mjs tools/*.test.mjs`);
  L.push('├─ electron/                   native shell (WebContentsView browser path, v0.51+)');
  L.push('├─ context/                    machine maps (app-map.json — regenerated each build)');
  L.push('└─ protocol/                   on-chain / iNFT protocol material');
  L.push('```');
  L.push('');
  L.push('## How to stay current');
  L.push('');
  L.push('- **Cheap check**: read the stamp line above. New commit/date ⇒ re-read this tree and');
  L.push('  the `AUTO PANELS` block of AGENTS.md before assuming anything about the app.');
  L.push('- **What exactly changed**: in the repo, `git log --oneline -10` names the last waves;');
  L.push('  in the workspace, `ls -lt` shows which files the last sync refreshed.');
  L.push('- **Live ground truth beats any map**: `app_rpc`/panels answer for the RUNNING app;');
  L.push('  this tree answers for the code. When they disagree, the running app wins (§5 of');
  L.push('  AGENTS.md: RPC ok is not truth — verify on screen).');
  L.push('');
  const md = L.join('\n');
  writeFileSync(OUT, md);
  if (!silent) console.log('structure-tree → agent/STRUCTURE.md · ' + sha);
  return { ok: true, out: OUT, sha };
}

if (import.meta.url === `file://${process.argv[1]}`) genStructureTree();
